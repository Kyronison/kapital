import type { SiteInfo } from '@kapital/protocol';
import { useSyncExternalStore } from 'react';
import { useSite } from '../site.js';

export type LegalDoc = 'privacy' | 'consent';

/** Редакция документов: меняется вместе с их текстом. */
const EDITION = '28 октября 2026 г.';

const parse = (): LegalDoc | null => {
  const id = location.hash.replace(/^#\/?/, '');
  return id === 'privacy' || id === 'consent' ? id : null;
};
const subscribe = (cb: () => void) => {
  window.addEventListener('hashchange', cb);
  return () => window.removeEventListener('hashchange', cb);
};

/** Документы открываются по адресу /#/privacy и /#/consent, в том числе без входа. */
export const useLegalDoc = (): LegalDoc | null => useSyncExternalStore(subscribe, parse);

/** Знак возрастной категории (436-ФЗ) и ссылки на документы: внизу экрана входа и кабинета. */
export function LegalFooter() {
  return (
    <footer className="legal-footer muted">
      <span className="age-mark" title="Информационная продукция для детей старше 12 лет">12+</span>
      <a href="#/privacy">Политика конфиденциальности</a>
      <a href="#/consent">Согласие на обработку данных</a>
      <span>Игра, а не инвестиционная рекомендация</span>
    </footer>
  );
}

export function LegalPage({ doc }: { doc: LegalDoc }) {
  const site = useSite();
  return (
    <main className="legal">
      <a className="link" href="#/">← Вернуться в игру</a>
      {site && (doc === 'privacy' ? <Privacy site={site} /> : <Consent site={site} />)}
      <LegalFooter />
    </main>
  );
}

